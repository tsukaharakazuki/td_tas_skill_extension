SELECT CAST(NULL AS VARCHAR) AS product_id, CAST(NULL AS VARCHAR) AS item_name,
       CAST(NULL AS VARCHAR) AS item_url, CAST(NULL AS VARCHAR) AS image_url,
       CAST(NULL AS VARCHAR) AS brand, CAST(NULL AS DOUBLE) AS price,
       CAST(NULL AS DOUBLE) AS original_price, FALSE AS published,
       FALSE AS available, FALSE AS low_stock
